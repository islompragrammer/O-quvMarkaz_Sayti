watch(locale, (value) => {
  if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, value)
})

export function setLocale(value) {
  locale.value = value === 'ru' ? 'ru' : 'uz'
}

export function applyTranslations(root, value = locale.value) {
  if (!root || typeof document === 'undefined') return
  const translations = value === 'ru'
    ? russianText
    : Object.fromEntries(Object.entries(russianText).map(([uzbek, russian]) => [russian, uzbek]))
  const entries = Object.entries(translations).sort(([left], [right]) => right.length - left.length)
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node
  while ((node = walker.nextNode())) {
    const translated = entries.reduce((text, [source, target]) => text.replaceAll(source, target), node.nodeValue)
    if (translated !== node.nodeValue) node.nodeValue = translated
  }
  root.querySelectorAll?.('[placeholder], [aria-label], [title]').forEach((element) => {
    for (const attribute of ['placeholder', 'aria-label', 'title']) {
      const current = element.getAttribute(attribute)
      const translated = current && translations[current]
      if (translated) element.setAttribute(attribute, translated)
    }
  })
}

export function useLocalizedDOM(root) {
  const apply = () => applyTranslations(root.value)
  onMounted(apply)
  onUpdated(apply)
  watch(locale, async () => {
    await nextTick()
    apply()
  })
}